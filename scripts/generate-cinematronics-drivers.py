"""Generate ROM checksums and digital input wiring from the locked BSD MAME driver.

Only metadata is generated, never ROM bytes. Manual hardware policy is kept
small and explicit here; unusual analog/mux hardware is handled by CineBoard.
"""
from pathlib import Path
import copy
import hashlib
import json
import re
root = Path(__file__).resolve().parents[1]
source = root / 'deps/mame-reference/src/mame/cinematronics/cinemat.cpp'
text = source.read_text(encoding='utf-8')
port_blocks = dict(re.findall(r'INPUT_PORTS_START\(\s*(\w+)\s*\)(.*?)INPUT_PORTS_END', text, re.S))
rom_blocks = dict(re.findall(r'ROM_START\(\s*(\w+)\s*\)(.*?)ROM_END', text, re.S))
games = re.findall(r'^GAMEL?\(\s*\d+,\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*\w+,\s*\w+,\s*([^,]+),\s*"[^"]*",\s*"([^"]+)"', text, re.M)
assert len(games) == 26, len(games)
# Existing normalized pad layout: A/B/X/Y, SELECT/START, UP/DOWN/LEFT/RIGHT, L/R.
pads = {'IPT_BUTTON1':1, 'IPT_BUTTON2':2, 'IPT_BUTTON3':4, 'IPT_BUTTON4':8,
        'IPT_JOYSTICK_UP':64, 'IPT_JOYSTICK_DOWN':128, 'IPT_JOYSTICK_LEFT':256,
        'IPT_JOYSTICK_RIGHT':512, 'IPT_START1':32|1024, 'IPT_START2':2048,
        'IPT_JOYSTICKLEFT_UP':64, 'IPT_JOYSTICKLEFT_DOWN':128,
        'IPT_JOYSTICKLEFT_LEFT':256, 'IPT_JOYSTICKLEFT_RIGHT':512,
        'IPT_JOYSTICKRIGHT_UP':8, 'IPT_JOYSTICKRIGHT_DOWN':1,
        'IPT_JOYSTICKRIGHT_LEFT':4, 'IPT_JOYSTICKRIGHT_RIGHT':2}
def ports(name):
    block = port_blocks[name]
    include = re.search(r'PORT_INCLUDE\(\s*(\w+)\s*\)', block)
    result = copy.deepcopy(ports(include[1])) if include else {'INPUTS':{}, 'SWITCHES':{}}
    current = None
    for line in block.splitlines():
        p = re.search(r'PORT_(?:START|MODIFY)\("(\w+)"\)', line)
        if p: current = p[1]
        if current not in result: continue
        dip = re.search(r'PORT_DIPNAME\(\s*(0x[\da-f]+),\s*(0x[\da-f]+)', line)
        bit = re.search(r'PORT_(?:BIT|DIPUNUSED_DIPLOC|SERVICE_DIPLOC|SERVICE)\(\s*(0x[\da-f]+),\s*IP_ACTIVE_(LOW|HIGH)(?:,\s*(IPT_\w+))?', line)
        if not dip and not bit: continue
        mask = int((dip or bit)[1],16)
        for old in list(result[current]):
            if old & mask: del result[current][old]
        if dip: result[current][mask] = (int(dip[2],16),0,0,0); continue
        player = re.search(r'PORT_PLAYER\((\d)\)', line)
        player = int(player[1])-1 if player else 0
        kind = bit[3] or ''
        pad = pads.get(kind,0)
        key = 0
        if kind == 'IPT_OTHER':
            k = re.search(r'PORT_CODE\(KEYCODE_(\w+)\)', line)
            if k:
                code = k[1].replace('_PAD','')
                key = ord(code.lower()) if len(code)==1 else {'STOP':ord('.'),'SLASH':ord('/'),'COMMA':ord(',')}.get(code,0)
        result[current][mask] = (mask if bit[2]=='LOW' else 0,pad,player,key)
    return result

output = ['// Generated by scripts/generate-cinematronics-drivers.py; DO NOT EDIT.',
          '// Metadata from MAME cinemat.cpp, BSD-3-Clause, Aaron Giles.',
          '// Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()]
manifest = []
initializers = []
for ident, parent, machine, inputs, orientation, title in games:
    block = rom_blocks[ident]
    main = re.search(r'ROM_REGION\(\s*(0x[\da-f]+),\s*"maincpu",\s*0\s*\)(.*?)(?=ROM_REGION|CCPU_PROMS|$)',block,re.S)
    assert main, ident
    size = int(main[1],16)
    chips=[]
    for line in main[2].splitlines():
        if not re.search(r'ROM(?:X)?_LOAD',line): continue
        rom=re.search(r'ROM(?:X_LOAD|_LOAD16_BYTE)\(\s*"([^"]+)",\s*(0x[\da-f]+),\s*(0x[\da-f]+),\s*CRC\(([\da-f]+)\)',line)
        assert rom, line
        chip=dict(name=rom[1],offset=int(rom[2],16),size=int(rom[3],16),crc=int(rom[4],16),
                  nibble=4 if 'NIBBLE_HI' in line else 0 if 'NIBBLE_LO' in line else -1)
        assert chip['offset']+(chip['size']-1)*2 < size
        chips.append(chip)
    assert chips, ident
    output.append('static constexpr RomChip chips_'+ident+'[] = {')
    for c in chips: output.append('    {"%s",0x%08xu,0x%x,0x%x,%d},'%(c['name'],c['crc'],c['offset'],c['size'],c['nibble']))
    output.append('};')
    pinmap=ports(inputs)
    defaults=[sum(x[0] for x in pinmap[p].values()) for p in ('INPUTS','SWITCHES')]
    bindings=[]
    for p, port in enumerate(('INPUTS','SWITCHES')):
        for mask, (_,pad,player,key) in pinmap[port].items():
            if pad or key: bindings.append((mask,pad,p,player,key))
    output.append('static constexpr InputBinding inputs_'+ident+'[] = {')
    for binding in bindings: output.append('    {%s},'%(','.join(str(n) for n in binding)))
    output.append('};')
    mach = 'wotw' if machine=='wotwc' else machine
    video = {'sundance':'gray16','solarq':'gray64','boxingb':'rgb444','wotwc':'rgb444','qb3':'rgb233'}.get(machine,'mono')
    width,height={'boxingb':(1024,788),'wotw':(1120,767),'demon':(1024,805),'qb3':(1120,780)}.get(machine,(1023,767))
    jmi=machine not in ('spacewar','speedfrk','tailg')
    orientation_bits=7 if 'ROT270' in orientation else 3 if 'FLIP_X' in orientation else 2
    initializers.append('    {"%s","%s","%s",Machine::%s,VectorMode::%s,%d,%d,%d,0x%04x,0x%02x,%s,%d,false,chips_%s,%d,inputs_%s,%d},'%
         (ident,title,'' if parent=='0' else parent,mach,video,size,width,height,*defaults,str(jmi).lower(),orientation_bits,ident,len(chips),ident,len(bindings)))
    manifest.append(dict(id=ident,parent=parent,machine=mach,title=title,rom_size=size,video=video,jmi=jmi,
                         width=width,height=height,input_default=defaults[0],switches=defaults[1],chips=chips,bindings=bindings))
output += ['const GameProfile game_profiles[] = {'] + initializers
output += ['    {"warrior4j","Warrior 4 Joystick v2","warrior",Machine::warrior,VectorMode::mono,8192,1023,767,0xffff,0xfa,true,2,true,nullptr,0,inputs_warrior,10},',
           '};','const size_t game_profile_count = sizeof(game_profiles)/sizeof(game_profiles[0]);']
# Do not encode a manually guessed binding count for the modified ROM.
output[-3] = output[-3].replace('inputs_warrior,10','inputs_warrior,static_cast<uint8_t>(sizeof(inputs_warrior)/sizeof(inputs_warrior[0]))')
(root/'core/cinematronics_profiles.inc').write_text('\n'.join(output)+'\n',encoding='utf-8')
(root/'rom-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print('Generated',len(games),'MAME sets plus Warrior 4J; all chip bounds checked.')
